// Слабое соединение (CMO 23.11.2026): только явная экономия трафика или 2G – ролики не грузим, оставляем заставки
// и конечные кадры, фото других кейсов заранее не подгружаем. 3G сюда не входит: Chrome ставит «3g» по задержке даже
// на нормальном Wi-Fi, и на этом режиме выключалась анимация второго экрана. Где API нет (Safari) – соединение нормальное.
const c = (navigator as any).connection;
export const slowNet: boolean = !!c && (c.saveData === true || /(^|-)2g$/.test(c.effectiveType || ""));
